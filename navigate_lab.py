    # 1. Applicant Profile Summary
    # 2. Identified Government Schemes
    # 3. Eligibility Analysis
    # 4. Scheme Comparison
    # 5. Required Documents
    # 6. Missing Information
    # 7. Step-by-Step Application Guidance
    # 8. Official Websites and Sources
