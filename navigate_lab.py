# 4. HELPER FUNCTIONS (SAFE TEXT, SOURCES, GENERATION WITH RETRY)
def get_text(response):
    try:
        return response.text or ""
    except Exception:
        return ""


def get_sources(response):
    """Collect Google Search grounding sources (title - url)."""
    found = []
    try:
        meta = response.candidates[0].grounding_metadata
        for chunk in (meta.grounding_chunks or []):
            if chunk.web and chunk.web.uri:
                found.append(f"{chunk.web.title} - {chunk.web.uri}")
    except Exception:
        pass
    return list(dict.fromkeys(found))


def generate_ai_response(prompt, use_live_search=False, retries=3):
    """Returns (text, sources). Retries on API errors; falls back to no-search."""
    tools = [types.Tool(google_search=types.GoogleSearch())] if use_live_search else None
    config = types.GenerateContentConfig(temperature=0.2, tools=tools)

    last_error = None
    for attempt in range(retries):
        try:
            response = client.models.generate_content(
                model=MODEL_NAME, contents=prompt, config=config
            )
            text = get_text(response)
            if text.strip():
                return text, get_sources(response)
            last_error = "Empty response"
        except Exception as e:
            last_error = e
        time.sleep(4 * (attempt + 1))

    if use_live_search:
        print("  (Live search failed, retrying without search...)")
        return generate_ai_response(prompt, use_live_search=False, retries=2)

    return f"[AI generation failed: {last_error}]", []


