for filename in uploaded_files.keys():
    extension = filename.lower().split(".")[-1]
    print("\nProcessing:", filename)
    extracted_text = ""

    try:
        if extension == "pdf":
            pdf = fitz.open(filename)
            for page_number, page in enumerate(pdf):
                page_text = page.get_text().strip()
                if page_text:
                    extracted_text += f"\nPage {page_number + 1}\n{page_text}\n"
                else:
                    # Scanned page -> Gemini Vision OCR
                    pix = page.get_pixmap(matrix=fitz.Matrix(1.5, 1.5))
                    image_path = f"/tmp/page_{uuid.uuid4().hex}.png"
                    pix.save(image_path)
                    try:
                        extracted_text += f"\nPage {page_number + 1}\n" + \
                            extract_image_information(image_path) + "\n"
                    except Exception as e:
                        print("Scanned page warning:", e)
                    finally:
                        if os.path.exists(image_path):
                            os.remove(image_path)
            pdf.close()

        elif extension in ["png", "jpg", "jpeg", "webp"]:
            extracted_text = extract_image_information(filename)

        else:
            print("Unsupported file skipped:", filename)
            continue

    except Exception as e:
        print("Could not process", filename, "->", e)
        continue

    if extracted_text.strip():
        document_sources.append(filename)
        words = extracted_text.split()
        chunk_size, overlap = 180, 35
        for i in range(0, len(words), chunk_size - overlap):
            chunk = " ".join(words[i:i + chunk_size])
            if len(chunk.strip()) > 30:
                document_chunks.append({"text": chunk, "source": filename})

